import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { InMemoryTransport } from '@modelcontextprotocol/sdk/inMemory.js';
import { resolveStartup } from '../dist/config.js';
import { loadSnapshot, buildPreviewServer, CONFIGURE_HINT } from '../dist/preview.js';

const root = new URL('../', import.meta.url);

/**
 * Preview mode exists so the server can describe itself before anyone has
 * configured it. Two things have to stay true: an unconfigured process answers
 * the listings, and a half-configured one still fails loudly instead of quietly
 * showing a preview that looks like a working server.
 */

/** Run a body with M00N_* set exactly as given, and nothing else. */
function withEnv(vars, body) {
  const saved = {};
  const keys = ['M00N_API_URL', 'M00N_API_KEY'];
  for (const k of keys) {
    saved[k] = process.env[k];
    delete process.env[k];
  }
  for (const [k, v] of Object.entries(vars)) process.env[k] = v;
  try {
    return body();
  } finally {
    for (const k of keys) {
      if (saved[k] === undefined) delete process.env[k];
      else process.env[k] = saved[k];
    }
  }
}

const VALID_URL = 'https://m00nreport.com';
const VALID_KEY = 'm00n_mcp_0000000000000000000000000000';

test('no configuration at all means preview', () => {
  withEnv({}, () => assert.equal(resolveStartup().mode, 'preview'));
});

test('whitespace-only values count as absent', () => {
  // A YAML block or a shell export can leave a space behind. That is still
  // nobody having configured anything.
  withEnv({ M00N_API_URL: '  ', M00N_API_KEY: '\t' }, () =>
    assert.equal(resolveStartup().mode, 'preview'),
  );
});

test('a URL with no key is a mistake, not a preview', () => {
  // The failure this guards: someone half way through configuring gets a server
  // that starts and lists tools, and only finds out when every call is refused.
  withEnv({ M00N_API_URL: VALID_URL }, () => {
    assert.throws(() => resolveStartup(), /M00N_API_KEY/);
  });
});

test('a key with no URL is a mistake, not a preview', () => {
  withEnv({ M00N_API_KEY: VALID_KEY }, () => {
    assert.throws(() => resolveStartup(), /M00N_API_URL/);
  });
});

test('a key without the m00n_mcp_ prefix still fails', () => {
  // A project API key pasted where an MCP key belongs. Preview must not swallow it.
  withEnv({ M00N_API_URL: VALID_URL, M00N_API_KEY: 'sk_live_not_an_mcp_key' }, () => {
    assert.throws(() => resolveStartup(), /m00n_mcp_/);
  });
});

test('a malformed URL still fails', () => {
  withEnv({ M00N_API_URL: 'not-a-url', M00N_API_KEY: VALID_KEY }, () => {
    assert.throws(() => resolveStartup(), /M00N_API_URL/);
  });
});

test('a valid pair starts live', () => {
  withEnv({ M00N_API_URL: VALID_URL, M00N_API_KEY: VALID_KEY }, () => {
    const startup = resolveStartup();
    assert.equal(startup.mode, 'live');
    assert.equal(startup.config.apiUrl, VALID_URL);
  });
});

const snapshot = loadSnapshot();

test('the snapshot has every section the server advertises', () => {
  for (const key of ['tools', 'prompts', 'resources', 'resourceTemplates']) {
    assert.ok(Array.isArray(snapshot[key]), `${key} is not an array`);
  }
});

test('the snapshot is not empty', () => {
  // An empty snapshot would make preview mode advertise a server that does
  // nothing, which is worse than not starting.
  assert.ok(snapshot.tools.length > 0);
  assert.ok(snapshot.prompts.length > 0);
});

test('every snapshot tool is usable as a tool definition', () => {
  for (const tool of snapshot.tools) {
    assert.ok(tool.name, 'tool with no name');
    assert.ok(tool.description, `${tool.name} has no description`);
    assert.ok(tool.inputSchema, `${tool.name} has no inputSchema`);
    assert.equal(typeof tool.inputSchema, 'object');
  }
});

test('snapshot tool names are unique', () => {
  const names = snapshot.tools.map((t) => t.name);
  assert.equal(new Set(names).size, names.length);
});

test('the snapshot carries no credential', () => {
  // It is generated by talking to a real instance with a real key, and it ships
  // inside the published package.
  //
  // The header NAME is not a secret and the instructions legitimately tell a
  // client to send it, so this looks for key VALUES: the prefix followed by a
  // body long enough to be one. A real key is 57 characters.
  const text = JSON.stringify(snapshot);
  assert.doesNotMatch(text, /m00n_mcp_[A-Za-z0-9_-]{16,}/);
});

/** A client wired to a preview server over an in-memory pair. */
async function connectPreview() {
  const server = buildPreviewServer(snapshot);
  const client = new Client({ name: 'preview-test', version: '1.0.0' }, { capabilities: {} });
  const [clientTransport, serverTransport] = InMemoryTransport.createLinkedPair();
  await Promise.all([server.connect(serverTransport), client.connect(clientTransport)]);
  return { client, server };
}

test('an unconfigured server answers tools/list', async () => {
  const { client, server } = await connectPreview();
  try {
    const result = await client.listTools();
    assert.equal(result.tools.length, snapshot.tools.length);
    assert.deepEqual(
      result.tools.map((t) => t.name).sort(),
      snapshot.tools.map((t) => t.name).sort(),
    );
  } finally {
    await server.close();
  }
});

test('listed tools carry exactly the fields a tool definition may have', async () => {
  // Both call sites project through src/list-shapes.ts, so the compiler is what
  // keeps them identical. This asserts the wire contract itself: an extra field
  // arriving from an instance must be dropped, not passed through.
  const allowed = new Set(['name', 'description', 'inputSchema', 'annotations']);
  const required = ['name', 'description', 'inputSchema'];
  const { client, server } = await connectPreview();
  try {
    const { tools } = await client.listTools();
    for (const tool of tools) {
      for (const key of Object.keys(tool)) {
        assert.ok(allowed.has(key), `unexpected field ${key} on ${tool.name}`);
      }
      for (const key of required) {
        assert.ok(key in tool, `${tool.name} is missing ${key}`);
      }
    }
  } finally {
    await server.close();
  }
});

test('an unconfigured server answers prompts/list and resources/list', async () => {
  const { client, server } = await connectPreview();
  try {
    const prompts = await client.listPrompts();
    assert.equal(prompts.prompts.length, snapshot.prompts.length);
    if (snapshot.resources.length > 0) {
      const resources = await client.listResources();
      assert.equal(resources.resources.length, snapshot.resources.length);
    }
  } finally {
    await server.close();
  }
});

test('calling a real tool is refused, and says how to fix it', async () => {
  const { client, server } = await connectPreview();
  try {
    const name = snapshot.tools[0].name;
    const result = await client.callTool({ name, arguments: {} });
    assert.equal(result.isError, true);
    assert.match(result.content[0].text, /M00N_API_URL/);
    assert.match(result.content[0].text, /M00N_API_KEY/);
    assert.ok(result.content[0].text.includes(name));
  } finally {
    await server.close();
  }
});

test('an unknown tool is named as unknown, not as unconfigured', async () => {
  // Otherwise a typo and a missing key produce the same message, and the caller
  // goes looking for the wrong problem.
  const { client, server } = await connectPreview();
  try {
    const result = await client.callTool({ name: 'no_such_tool_at_all', arguments: {} });
    assert.equal(result.isError, true);
    assert.match(result.content[0].text, /Unknown tool/);
  } finally {
    await server.close();
  }
});

test('the configure hint names both variables', () => {
  assert.match(CONFIGURE_HINT, /M00N_API_URL/);
  assert.match(CONFIGURE_HINT, /M00N_API_KEY/);
});

/**
 * The snapshot only reaches a user if two hand-maintained lines carry it: the
 * npm "files" list and a COPY in the Dockerfile. Delete either and the suite
 * stays green while the feature dies at startup. The main repo learned this
 * three times over with Dockerfile.api before a test closed it.
 */

test('the npm package ships the snapshot', () => {
  const pkg = JSON.parse(readFileSync(new URL('package.json', root), 'utf8'));
  assert.ok(
    pkg.files.includes('preview-snapshot.json'),
    'preview-snapshot.json is not in package.json "files", so it will not be published',
  );
});

test('the Docker image ships the snapshot', () => {
  const dockerfile = readFileSync(new URL('Dockerfile', root), 'utf8');
  assert.match(
    dockerfile,
    /^COPY preview-snapshot\.json/m,
    'the Dockerfile does not COPY preview-snapshot.json, so the image cannot start unconfigured',
  );
});

test('the image does not run as root', () => {
  // A directory that builds and scores containers is the audience that checks.
  const dockerfile = readFileSync(new URL('Dockerfile', root), 'utf8');
  assert.match(dockerfile, /^USER node$/m);
});

test('neither server re-inlines the list projections', () => {
  // They are shared in src/list-shapes.ts so the compiler keeps the live path and
  // preview mode identical. Inlining one again silently reopens the drift.
  for (const file of ['src/server.ts', 'src/preview.ts']) {
    const source = readFileSync(new URL(file, root), 'utf8');
    assert.match(source, /from '\.\/list-shapes\.js'/, `${file} no longer imports the shapes`);
    assert.doesNotMatch(
      source,
      /inputSchema:\s*tool\.inputSchema/,
      `${file} inlines the tool projection again`,
    );
  }
});
